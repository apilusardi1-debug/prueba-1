// Criterio para las piscinas naturales (el mismo que marca la tabla de origen):
// una marea baja de día, entre las 06:00 y las 17:00, de 0,60 m o menos.
// Hasta 0,40 m es ideal; entre 0,41 y 0,60 m, posible.
const HORA_DESDE = '06:00'
const HORA_HASTA = '17:00'
const ALTURA_POSIBLE = 0.6
const ALTURA_IDEAL = 0.4

export const ESTADOS_PISCINAS = {
  ideal:   { id: 'ideal',   label: 'Ideal' },
  posible: { id: 'posible', label: 'Posible' },
  // Sin marea baja de día no hay piscinas naturales, pero sí todos los demás paseos:
  // el texto invita a esos paseos en vez de decir "no apta" (pedido de Abril, 2026-10-14).
  no:      { id: 'no',      label: 'Otros paseos' },
}

const FECHAS = Object.keys(MAREAS).sort()
export const PRIMER_DIA = FECHAS[0]
export const ULTIMO_DIA = FECHAS[FECHAS.length - 1]

// Todas las mareas en una sola lista, para saber si cada una es alta o baja
// comparándola con la siguiente (o la anterior, si es la última de la tabla).
const TODAS = FECHAS.flatMap(fecha =>
  MAREAS[fecha].split('|').map(p => {
    const [hora, altura] = p.trim().split(' ')
    return { fecha, hora, altura: parseFloat(altura) }
  })
).map((m, i, lista) => {
  const vecina = lista[i + 1] || lista[i - 1]
  return { ...m, tipo: m.altura > vecina.altura ? 'alta' : 'baja' }
})

// "AAAA-MM-DD" de hoy en la hora de Pernambuco (no la del navegador del visitante)
export function hoyEnDestino() {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Recife' }).format(new Date())
}

function sumarDias(fechaISO, n) {
  const d = new Date(`${fechaISO}T12:00:00Z`)
  d.setUTCDate(d.getUTCDate() + n)
  return d.toISOString().slice(0, 10)
}

// Las mareas de un día, con la mejor marea baja para las piscinas y su estado.
// null si ese día no está cargado.
export function diaDeMarea(fechaISO) {
  if (!MAREAS[fechaISO]) return null
  const mareas = TODAS.filter(m => m.fecha === fechaISO)
  const aptas = mareas.filter(m => m.tipo === 'baja' && m.hora >= HORA_DESDE && m.hora <= HORA_HASTA && m.altura <= ALTURA_POSIBLE)
  const mejor = aptas.sort((a, b) => a.altura - b.altura)[0] || null
  const estado = !mejor ? ESTADOS_PISCINAS.no : mejor.altura <= ALTURA_IDEAL ? ESTADOS_PISCINAS.ideal : ESTADOS_PISCINAS.posible
  return { fecha: fechaISO, mareas, mejor, estado }
}

// Los próximos `cantidad` días cargados desde `desde` (incluido)
export function proximosDias(desde, cantidad) {
  const dias = []
  for (let i = 0; i < cantidad; i++) {
    const dia = diaDeMarea(sumarDias(desde, i))
    if (dia) dias.push(dia)
  }
  return dias
}

// El primer día desde `desde` en que se puede ir a las piscinas
export function proximaVentana(desde) {
  for (let fecha = desde; fecha <= ULTIMO_DIA; fecha = sumarDias(fecha, 1)) {
    const dia = diaDeMarea(fecha)
    if (dia?.mejor) return dia
  }
  return null
}

// "0,32 m" (en inglés, "0.32 m")
export function formatoAltura(altura, lang = 'es') {
  const n = altura.toFixed(2)
  return `${lang === 'en' ? n : n.replace('.', ',')} m`
}
